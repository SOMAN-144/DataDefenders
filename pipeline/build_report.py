"""Generate docs/STATISTICAL_REPORT.md from the database, so its figures cannot drift."""
from __future__ import annotations

import sqlite3

from common import ROOT

DB = ROOT / "database" / "cybercrime.db"
OUT = ROOT / "docs" / "STATISTICAL_REPORT.md"


def table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def n(value: float | None) -> str:
    return "n/a" if value is None else f"{value:,.0f}"


def main() -> None:
    con = sqlite3.connect(DB)
    q = con.execute
    nat = q(
        """SELECT c.year, c.reported_cases, p.population FROM cybercrime_statistics c
           JOIN population_statistics p ON p.state_id = c.state_id AND p.year = c.year
           WHERE c.state_id = 0 ORDER BY c.year"""
    ).fetchall()
    rows = []
    for i, (year, cases, pop) in enumerate(nat):
        growth = f"{(cases - nat[i - 1][1]) / nat[i - 1][1] * 100:+.1f}%" if i else "n/a"
        rows.append([year, n(cases), growth, f"{cases / pop * 1e5:.1f}"])
    latest = nat[-1][0]
    cumulative = sum(r[1] for r in nat)
    annual = (nat[-1][1] / nat[0][1]) ** (1 / (nat[-1][0] - nat[0][0])) - 1

    states = q(
        """SELECT s.state_name, c.reported_cases, p.population FROM cybercrime_statistics c
           JOIN states s USING (state_id)
           JOIN population_statistics p ON p.state_id = c.state_id AND p.year = c.year
           WHERE c.state_id <> 0 AND c.year = ? AND c.reported_cases IS NOT NULL""", (latest,)
    ).fetchall()
    top_cases = sorted(states, key=lambda r: -r[1])[:10]
    top_rate = sorted(states, key=lambda r: -r[1] / r[2])[:10]
    national_latest = nat[-1][1]

    heads = q(
        """SELECT h.label, s.reported_cases FROM crime_head_statistics s JOIN crime_heads h USING (head_id)
           WHERE s.state_id = 0 AND s.year = ? AND h.level = 1 AND s.reported_cases > 0
           ORDER BY 2 DESC LIMIT 10""", (latest,)
    ).fetchall()
    subs = q(
        """SELECT h.label, s.reported_cases FROM crime_head_statistics s JOIN crime_heads h USING (head_id)
           WHERE s.state_id = 0 AND s.year = ? AND h.parent_id = 'fraud_total' ORDER BY 2 DESC""", (latest,)
    ).fetchall()
    fraud = q(
        """SELECT f.year, f.reported_cases, t.reported_cases FROM motive_statistics f
           JOIN motive_statistics t ON t.year = f.year AND t.state_id = 0 AND t.motive_id = 'total'
           WHERE f.state_id = 0 AND f.motive_id = 'fraud' ORDER BY f.year"""
    ).fetchall()
    growth = q(
        """SELECT h.label, a.reported_cases, b.reported_cases FROM crime_heads h
           JOIN crime_head_statistics a ON a.head_id = h.head_id AND a.year = 2021 AND a.state_id = 0
           JOIN crime_head_statistics b ON b.head_id = h.head_id AND b.year = ? AND b.state_id = 0
           WHERE h.level IN (1, 2) AND a.reported_cases >= 50""", (latest,)
    ).fetchall()
    growth = sorted(growth, key=lambda r: -(r[2] / r[1]))
    cagr = lambda r: f"{((r[2] / r[1]) ** (1 / (latest - 2021)) - 1) * 100:+.1f}%"

    regions = q(
        """SELECT s.region, SUM(c.reported_cases), SUM(p.population) FROM cybercrime_statistics c
           JOIN states s USING (state_id)
           JOIN population_statistics p ON p.state_id = c.state_id AND p.year = c.year
           WHERE c.state_id <> 0 AND c.year = ? GROUP BY s.region ORDER BY 2 DESC""", (latest,)
    ).fetchall()
    ncrp = q(
        "SELECT year, complaints, reported_financial_loss_crore FROM financial_statistics WHERE state_id = 0 ORDER BY year"
    ).fetchall()
    ncrp_states = q(
        """SELECT s.state_name, f.complaints, f.reported_financial_loss_crore, f.lien_amount_crore FROM financial_statistics f
           JOIN states s USING (state_id) WHERE f.state_id <> 0 ORDER BY 3 DESC LIMIT 10"""
    ).fetchall()
    cert = q("SELECT year, incidents, verification FROM cert_in_incidents ORDER BY year").fetchall()
    bank = q(
        "SELECT financial_year, frauds, amount_crore FROM bank_fraud_statistics WHERE area = 'Card/Internet' ORDER BY financial_year"
    ).fetchall()
    forecast = q("SELECT year, predicted, lower_95, upper_95, model FROM forecasts ORDER BY year").fetchall()
    models = q("SELECT model, mape, mean_error_pct, interval_coverage_pct, selected FROM forecast_models ORDER BY mape").fetchall()
    revisions = q("SELECT scope, year, published_values FROM revisions").fetchall()

    parts = [
        "# Statistical analysis report",
        "",
        "*Generated by `pipeline/build_report.py` from `database/cybercrime.db`. Do not edit by hand.*",
        "",
        "Reporting systems are analysed separately and never added together. Rates use the mid-year population NCRB printed for that year.",
        "",
        "## 1. National registered cases (NCRB)",
        "",
        table(["Year", "Cases", "Growth", "Rate per 100,000"], rows),
        "",
        f"Cases rose from {n(nat[0][1])} in {nat[0][0]} to {n(nat[-1][1])} in {latest}, a compound rate of {annual * 100:.1f}% a year. "
        f"The {nat[0][0]}-{latest} total is {n(cumulative)}. The peak is {latest}, the latest year published.",
        "",
        f"## 2. States and UTs, {latest}",
        "",
        "### By reported cases",
        "",
        table(["State/UT", "Cases", "Share of India"], [[r[0], n(r[1]), f"{r[1] / national_latest * 100:.1f}%"] for r in top_cases]),
        "",
        "### By population-adjusted rate",
        "",
        table(["State/UT", "Rate per 100,000", "Cases"], [[r[0], f"{r[1] / r[2] * 1e5:.1f}", n(r[1])] for r in top_rate]),
        "",
        f"Telangana and Karnataka together hold {sum(r[1] for r in states if r[0] in ('Telangana', 'Karnataka')) / national_latest * 100:.1f}% of cases. "
        "A high count is not evidence of more crime alone: NCRB warns against comparing States purely on these figures, because registration practice differs.",
        "",
        "### By region (Zonal Councils, with the North-East separate; a project grouping)",
        "",
        table(["Region", "Cases", "Rate per 100,000"], [[r[0], n(r[1]), f"{r[1] / r[2] * 1e5:.1f}"] for r in regions]),
        "",
        f"## 3. Crime categories, {latest}",
        "",
        "### Largest crime heads (Table 9A.2)",
        "",
        table(["Crime head", "Cases", "Share"], [[r[0], n(r[1]), f"{r[1] / national_latest * 100:.1f}%"] for r in heads]),
        "",
        "### Sub-heads of 'Fraud'",
        "",
        table(["Sub-head", "Cases"], [[r[0], n(r[1])] for r in subs]),
        "",
        "Gaming, investment, vishing and e-wallet/UPI sub-heads first appear in 2024, so they have no history.",
        "",
        "### Fraud as a recorded motive (Table 9A.3)",
        "",
        table(["Year", "Fraud motive", "All cases", "Share"], [[r[0], n(r[1]), n(r[2]), f"{r[1] / r[2] * 100:.1f}%"] for r in fraud]),
        "",
        "### Fastest-growing heads, 2021-2024 (at least 50 cases in 2021)",
        "",
        table(["Crime head", "2021", str(latest), "Compound annual growth"], [[r[0], n(r[1]), n(r[2]), cagr(r)] for r in growth[:10]]),
        "",
        "### Falling heads, 2021-2024",
        "",
        table(["Crime head", "2021", str(latest), "Compound annual growth"], [[r[0], n(r[1]), n(r[2]), cagr(r)] for r in growth[::-1][:8] if r[2] < r[1]]),
        "",
        "## 4. Financial impact (NCRP complaints)",
        "",
        table(
            ["Year", "Complaints", "Amount reported (crore)", "Average per complaint"],
            [[r[0], n(r[1]), f"Rs {n(r[2])}", f"Rs {n(r[2] * 1e7 / r[1])}"] for r in ncrp],
        ),
        "",
        f"Yearly amounts sum to Rs {n(sum(r[2] for r in ncrp))} crore. Amounts are as reported by complainants and are not verified losses. No average per NCRB case is calculated, because these are different incidents.",
        "",
        "### Top States by amount reported, 2023 (the only verified State table)",
        "",
        table(["State/UT", "Complaints", "Amount (crore)", "Lien (crore)"], [[r[0], n(r[1]), f"Rs {r[2]:,.1f}", f"Rs {r[3]:,.1f}"] for r in ncrp_states]),
        "",
        "## 5. Other official series",
        "",
        "### CERT-In incidents handled",
        "",
        table(["Year", "Incidents", "Source type"], [[r[0], n(r[1]), r[2]] for r in cert]),
        "",
        "### RBI: Card/Internet frauds reported by banks",
        "",
        table(["Financial year", "Frauds", "Amount (crore)"], [[r[0], n(r[1]), f"Rs {n(r[2])}"] for r in bank]),
        "",
        "## 6. Forecast (estimates, not statistics)",
        "",
        table(["Model", "MAPE", "Mean error", "95% interval coverage", "Selected"],
              [[r[0], f"{r[1]:.1f}%", f"{r[2]:+.1f}%", f"{r[3]:.0f}%", "Yes" if r[4] else ""] for r in models]),
        "",
        table(["Year", "Estimate", "95% low", "95% high"], [[r[0], n(r[1]), n(r[2]), n(r[3])] for r in forecast]),
        "",
        "Scored by rolling-origin backtest on published years. The selected model under-predicted on average and its nominal 95% interval covered too few actual values, so the true uncertainty is larger than the band shows.",
        "",
        "## 7. Revisions between NCRB editions",
        "",
        table(["Scope", "Year", "Values"], [list(r) for r in revisions]),
        "",
        "## 8. Change points",
        "",
        "- 2017 and 2019 show the sharpest national increases (see section 1). Reclassification and reporting changes cannot be ruled out from these tables alone.",
        "- Assam's count fell steeply after 2021, and West Bengal has a declining trend with a known 2019 data problem. These deserve cautious reading.",
        "- The NCRP amount tripled in 2024 and then fell slightly in 2025, while complaints kept rising, so the average per complaint fell in 2025.",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
